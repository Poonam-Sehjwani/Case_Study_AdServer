
-- Add an internal primary key to processed events.
ALTER TABLE processed_events
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE processed_events
    DROP CONSTRAINT processed_events_pkey;

ALTER TABLE processed_events
    ADD CONSTRAINT pk_processed_events PRIMARY KEY (id);

-- Event IDs must be unique within a retailer.
ALTER TABLE processed_events
    ADD CONSTRAINT uk_processed_events_tenant_event
    UNIQUE (retailer_id, event_id);

-- Store an anonymous customer identifier.
ALTER TABLE processed_events
    ADD COLUMN anonymous_customer_id VARCHAR(100);

CREATE INDEX idx_processed_events_tenant_campaign_time
    ON processed_events (retailer_id, campaign_id, event_time);

-- Add an internal primary key and tenant scope to campaign metrics.
ALTER TABLE campaign_metrics
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE campaign_metrics
    ADD COLUMN retailer_id VARCHAR(100) NOT NULL DEFAULT 'legacy';

ALTER TABLE campaign_metrics
    DROP CONSTRAINT campaign_metrics_pkey;

ALTER TABLE campaign_metrics
    ADD CONSTRAINT pk_campaign_metrics PRIMARY KEY (id);

ALTER TABLE campaign_metrics
    ADD CONSTRAINT uk_campaign_metrics_tenant_campaign
    UNIQUE (retailer_id, campaign_id);

-- Record ad clicks so later basket events can be attributed.
CREATE TABLE click_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retailer_id VARCHAR(100) NOT NULL,
    session_id VARCHAR(100) NOT NULL,
    anonymous_customer_id VARCHAR(100),
    campaign_id VARCHAR(100) NOT NULL,
    click_event_id VARCHAR(100) NOT NULL,
    clicked_at TIMESTAMPTZ NOT NULL,
    attributed_at TIMESTAMPTZ,
    CONSTRAINT uk_click_sessions_tenant_event
        UNIQUE (retailer_id, click_event_id)
);

CREATE INDEX idx_click_sessions_attribution
    ON click_sessions
       (retailer_id, session_id, campaign_id, clicked_at);
